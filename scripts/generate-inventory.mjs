import fs from 'node:fs';
import path from 'node:path';
import ts from 'typescript';
const root = path.resolve(import.meta.dirname, '..');
const files = [];
function walk(dir) {
  for (const entry of fs.readdirSync(path.join(root, dir), {withFileTypes:true})) {
    const file = `${dir}/${entry.name}`;
    if (entry.isDirectory()) walk(file);
    else if (/\.(ts|mjs)$/.test(file)) files.push(file);
  }
}
walk('extensions'); walk('scripts');
const rows = [], commands = new Set(), tools = new Set();
for (const file of files.sort()) {
  const source = fs.readFileSync(path.join(root,file),'utf8');
  rows.push({file,lines:source.split('\n').length});
  const ast = ts.createSourceFile(file,source,ts.ScriptTarget.Latest,true);
  function visit(node) {
    if (ts.isCallExpression(node)) {
      const name = node.expression.getText(ast);
      const arg = node.arguments[0];
      if (name.endsWith('.registerCommand') && arg && ts.isStringLiteral(arg)) commands.add(arg.text);
      if ((name === 'defineTool' || name.endsWith('.wrapTool')) && arg && ts.isObjectLiteralExpression(arg)) {
        for (const prop of arg.properties) if (ts.isPropertyAssignment(prop) && prop.name.getText(ast)==='name' && ts.isStringLiteral(prop.initializer)) tools.add(prop.initializer.text);
      }
    }
    ts.forEachChild(node,visit);
  }
  visit(ast);
}
const globalsSource = fs.readFileSync(path.join(root,'extensions/loops/goal-runtime-globals.ts'),'utf8');
const globals = [...globalsSource.split('export const GOAL_RUNTIME_GLOBAL_NAMES = [')[1].split('] as const')[0].matchAll(/"([^"]+)"/g)].map(match=>match[1]);
const tests = fs.readdirSync(path.join(root,'tests')).filter(file=>/\.test\.(ts|mjs)$/.test(file));
const output = `# Generated runtime inventory\n\nGenerated by \`node scripts/generate-inventory.mjs\`. Run with \`--check\` to detect drift. Counts describe files and literal registrations, not executed coverage.\n\n- Extension/script files: ${rows.length}\n- Extension/script lines: ${rows.reduce((total,row)=>total+row.lines,0)}\n- Top-level test files: ${tests.length}\n- Ambient bridge names: ${globals.length} (audit baseline: 179)\n- Commands: ${[...commands].sort().map(name=>'\`/'+name+'\`').join(', ')}\n- Tools: ${[...tools].sort().map(name=>'\`'+name+'\`').join(', ')}\n\n## Largest modules\n\n| Module | Lines |\n|---|---:|\n${rows.sort((a,b)=>b.lines-a.lines || a.file.localeCompare(b.file)).slice(0,10).map(row=>`| [${row.file}](../${row.file}) | ${row.lines} |`).join('\n')}\n\nSettings are defined in [SETTINGS.md](SETTINGS.md); supported host versions and process limits are defined in [COMPATIBILITY.md](COMPATIBILITY.md).\n`;
const target=path.join(root,'docs/RUNTIME-INVENTORY.md');
if(process.argv.includes('--check')) {
  if (!fs.existsSync(target) || fs.readFileSync(target,'utf8') !== output) { console.error('Runtime inventory is stale; run node scripts/generate-inventory.mjs'); process.exitCode=1; }
} else fs.writeFileSync(target,output);
